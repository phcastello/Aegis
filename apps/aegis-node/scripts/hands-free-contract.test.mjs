import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { test } from 'node:test';

const source = path => readFileSync(new URL(`../src-tauri/${path}`, import.meta.url), 'utf8');

test('hands-free selected capability keeps the closed app command on Android main only', () => {
  const config = JSON.parse(source('tauri.conf.json'));
  const capability = JSON.parse(source('capabilities/hands-free.json'));
  assert.equal(capability.identifier, 'android-hands-free');
  assert.ok(config.app.security.capabilities.includes(capability.identifier), 'A discovered capability is insufficient when selection is explicit.');
  assert.deepEqual(capability.platforms, ['android']);
  assert.deepEqual(capability.windows, ['main']);
  assert.deepEqual(capability.permissions, ['allow-node-hands-free']);
  assert.equal(capability.remote, undefined);
  assert.equal(capability.local ?? true, true);
  assert.equal(capability.webviews, undefined);
  const permission = source('permissions/autogenerated/node_hands_free.toml');
  assert.match(permission, /identifier\s*=\s*"allow-node-hands-free"[\s\S]*?commands\.allow\s*=\s*\["node_hands_free"\]/);
  assert.match(source('build.rs'), /AppManifest::new\(\)\.commands\(&\[[\s\S]*?"node_hands_free"[\s\S]*?\]\)/);
  assert.match(source('src/lib.rs'), /\.invoke_handler\(tauri::generate_handler!\[[\s\S]*?hands_free::node_hands_free,[\s\S]*?\]\)/);
});

test('Android framework gate runs real hands-free IPC before granting microphone or starting backend fixture', () => {
  const host = readFileSync(new URL('./android-notification-framework.mjs', import.meta.url), 'utf8');
  const invoke = host.indexOf("instrumentation('NodeHandsFreeStateIpcTest'");
  const fixture = host.indexOf("run(['reverse', 'tcp:18104'");
  assert.ok(invoke > 0);
  assert.ok(host.indexOf("'android.permission.RECORD_AUDIO'") < invoke);
  assert.ok(invoke < host.indexOf('permission(true);'));
  assert.ok(fixture < 0 || invoke < fixture);
  const android = source('gen/android/notificationFrameworkTest/shared/com/aegis/node/NodeHandsFreeStateIpcTest.kt');
  assert.ok(android.includes("__TAURI_INTERNALS__.invoke('node_hands_free',{operation:'state'})"));
  assert.doesNotMatch(android, /mockIPC|__TAURI_INTERNALS__\s*=/);
  assert.ok(android.includes('hands_free_real_ipc_initial_state'));
  assert.ok(host.includes("phases.has('hands_free_real_ipc_initial_state')"));
});
