//! The same capability selection and platform resolver used by generate_context!.
use std::collections::BTreeMap;
use tauri_utils::{
    acl::{self, capability::Capability, manifest::Manifest, resolved::Resolved, ExecutionContext},
    config::Config,
    platform::Target,
};

pub fn merge_config(base: &mut serde_json::Value, patch: &serde_json::Value) {
    if let Some(fields) = patch.as_object() {
        if !base.is_object() {
            *base = serde_json::json!({});
        }
        for (key, value) in fields {
            if value.is_null() {
                base.as_object_mut().unwrap().remove(key);
            } else {
                merge_config(&mut base[key], value);
            }
        }
    } else {
        *base = patch.clone();
    }
}

pub fn verify(
    config: &Config,
    manifests: &BTreeMap<String, Manifest>,
    files: BTreeMap<String, Capability>,
    target: Target,
) -> Result<(), &'static str> {
    // An empty selector would implicitly enable every discovered capability.
    if config.app.security.capabilities.is_empty() {
        return Err("explicit_capability_selection_required");
    }
    let selected =
        acl::get_capabilities(config, files, None).map_err(|_| "capability_selection_invalid")?;
    let resolved = Resolved::resolve(manifests, selected, target)
        .map_err(|_| "capability_resolution_invalid")?;
    if !resolved.has_app_acl {
        return Err("app_command_manifest_required");
    }
    let allowed = resolved.allowed_commands.get("node_hands_free");
    if target != Target::Android {
        return if allowed.is_none() {
            Ok(())
        } else {
            Err("hands_free_must_be_android_only")
        };
    }
    let grants = allowed
        .filter(|items| items.len() == 1)
        .ok_or("hands_free_not_authorized")?;
    let grant = &grants[0];
    if grant.context != ExecutionContext::Local
        || grant.windows.len() != 1
        || grant.windows[0].as_str() != "main"
        || !grant.webviews.is_empty()
        || resolved.denied_commands.contains_key("node_hands_free")
    {
        return Err("hands_free_scope_must_be_local_main_only");
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    fn fixture() -> (
        Config,
        BTreeMap<String, Manifest>,
        BTreeMap<String, Capability>,
    ) {
        let config: Config = serde_json::from_str(include_str!("tauri.conf.json")).unwrap();
        let capability: Capability =
            serde_json::from_str(include_str!("capabilities/hands-free.json")).unwrap();
        // Actual auto-generated command permission source, parsed with Tauri's own loader.
        let temporary =
            std::env::temp_dir().join(format!("aegis-acl-test-{}", uuid::Uuid::new_v4()));
        std::fs::create_dir(&temporary).unwrap();
        let permissions = acl::build::define_permissions(
            "permissions/autogenerated/node_hands_free.toml",
            "hands-free-contract",
            &temporary,
            |_| true,
        )
        .unwrap();
        std::fs::remove_dir_all(temporary).unwrap();
        let manifests =
            BTreeMap::from([(acl::APP_ACL_KEY.into(), Manifest::new(permissions, None))]);
        // Keep only this capability in selection; other existing app permissions are independent.
        let mut isolated = config;
        isolated.app.security.capabilities.retain(|entry| matches!(entry, tauri_utils::config::CapabilityEntry::Reference(id) if id=="android-hands-free"));
        assert!(
            !isolated.app.security.capabilities.is_empty(),
            "effective base configuration omits android-hands-free"
        );
        (
            isolated,
            manifests,
            BTreeMap::from([(capability.identifier.clone(), capability)]),
        )
    }
    #[test]
    fn selected_command_is_scoped_to_android_local_main() {
        let (config, manifests, files) = fixture();
        assert_eq!(
            verify(&config, &manifests, files.clone(), Target::Android),
            Ok(())
        );
        for target in [Target::Windows, Target::Linux, Target::Ios, Target::MacOS] {
            assert_eq!(verify(&config, &manifests, files.clone(), target), Ok(()));
        }
    }
    #[test]
    fn omitting_selection_fails_even_when_the_capability_file_exists() {
        let (mut config, manifests, files) = fixture();
        config.app.security.capabilities.clear();
        assert_eq!(
            verify(&config, &manifests, files, Target::Android),
            Err("explicit_capability_selection_required")
        );
    }
    #[test]
    fn explicit_selection_without_hands_free_fails_the_resolved_authority() {
        let (mut config, manifests, mut files) = fixture();
        let mut unrelated = files["android-hands-free"].clone();
        unrelated.identifier = "unrelated".into();
        unrelated.permissions.clear();
        files.insert(unrelated.identifier.clone(), unrelated);
        config.app.security.capabilities = vec![tauri_utils::config::CapabilityEntry::Reference(
            "unrelated".into(),
        )];
        assert_eq!(
            verify(&config, &manifests, files, Target::Android),
            Err("hands_free_not_authorized")
        );
    }
    #[test]
    fn broad_windows_webviews_origins_and_platforms_are_rejected() {
        let (config, manifests, files) = fixture();
        for patch in [
            serde_json::json!({"windows":["*"]}),
            serde_json::json!({"webviews":["main"]}),
            serde_json::json!({"remote":{"urls":["https://example.test"]}}),
        ] {
            let mut changed = files.clone();
            let mut json = serde_json::to_value(&changed["android-hands-free"]).unwrap();
            merge_config(&mut json, &patch);
            changed.insert(
                "android-hands-free".into(),
                serde_json::from_value(json).unwrap(),
            );
            assert!(verify(&config, &manifests, changed, Target::Android).is_err());
        }
        let mut changed = files;
        changed.get_mut("android-hands-free").unwrap().platforms = None;
        assert_eq!(
            verify(&config, &manifests, changed, Target::Windows),
            Err("hands_free_must_be_android_only")
        );
    }
    #[test]
    fn distribution_overlays_replace_arrays_and_cannot_remove_the_android_grant() {
        let (config, manifests, files) = fixture();
        let mut json = serde_json::to_value(config).unwrap();
        merge_config(
            &mut json,
            &serde_json::json!({"app":{"security":{"capabilities":[]}},"bundle":{"android":{"versionCode":8000003}}}),
        );
        assert_eq!(
            verify(
                &serde_json::from_value(json).unwrap(),
                &manifests,
                files,
                Target::Android
            ),
            Err("explicit_capability_selection_required")
        );
    }
}
