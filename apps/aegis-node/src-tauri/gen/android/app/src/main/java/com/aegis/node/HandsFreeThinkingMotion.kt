    fun sample(elapsedMs: Long, out: FloatArray) {
        require(out.size >= 6)
        val wrapped = elapsedMs % DURATION_MS
        val time = if (wrapped < 0L) wrapped + DURATION_MS else wrapped
        var lo = 0
        var hi = knots.size / STRIDE - 1
        while (hi - lo > 1) {
            val mid = (lo + hi) / 2
            if (knots[mid * STRIDE].toLong() <= time) lo = mid else hi = mid
        }
        val left = lo * STRIDE
        val right = hi * STRIDE
        val progress = (time - knots[left]).toFloat() / (knots[right] - knots[left])
        for (index in 0 until 6) {
            val begin = knots[left + 1 + index]
            val end = knots[right + 1 + index]
            out[index] = (begin + (end - begin) * progress) * .001f
        }
    }
